use eframe::egui::{Color32, Image, ImageSource, Response, Ui, Vec2};

/// 渲染标准的 Material Icons SVG 矢量图
pub fn render_svg_icon(ui: &mut Ui, svg_content: &str, size: f32, color: Color32) -> Response {
    let hex_color = format!("#{:02X}{:02X}{:02X}", color.r(), color.g(), color.b());
    let dynamic_svg = svg_content.replace("currentColor", &hex_color);
    
    let uri = format!("bytes://material_icon_{}_{}.svg", size as u32, hex_color);
    let image_source = ImageSource::Bytes {
        uri: uri.into(),
        bytes: dynamic_svg.into_bytes().into(),
    };

    let img = Image::new(image_source).fit_to_exact_size(Vec2::new(size, size));
    ui.add(img)
}

